import assert from 'node:assert/strict';
import {readFileSync,mkdirSync,writeFileSync} from 'node:fs';
import ts from 'typescript';
const dir=new URL('../.sites-runtime/media-tests/',import.meta.url);mkdirSync(dir,{recursive:true});
writeFileSync(new URL('media.mjs',dir),ts.transpileModule(readFileSync(new URL('../lib/call-media.ts',import.meta.url),'utf8'),{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText);
const {addRemoteTrack,playRemoteMedia}=await import(new URL('media.mjs',dir));
const tracks=[];
const stream={getTracks:()=>tracks,getVideoTracks:()=>tracks.filter(t=>t.kind==='video'),getAudioTracks:()=>tracks.filter(t=>t.kind==='audio'),addTrack:t=>tracks.push(t)};
addRemoteTrack(stream,{id:'audio',kind:'audio'});
addRemoteTrack(stream,{id:'video',kind:'video'});
addRemoteTrack(stream,{id:'audio',kind:'audio'});
assert.equal(tracks.length,2,'Separate streamless events preserve both tracks without duplicates');
let videoPlays=0,audioPlays=0;
const video={srcObject:null,muted:false,play:async()=>{videoPlays++;assert.equal(video.muted,true);}};
const audio={srcObject:null,muted:false,play:async()=>{audioPlays++;throw Object.assign(new Error('User gesture required'),{name:'NotAllowedError'});}};
assert.equal(await playRemoteMedia(video,audio,stream,true),true);
assert.equal(videoPlays,1,'Audio autoplay rejection does not prevent video playback');
assert.equal(audioPlays,1);
assert.equal(video.srcObject,stream);assert.equal(audio.srcObject,stream);
assert.equal(await playRemoteMedia(video,audio,stream,false),false);
assert.equal(videoPlays,2);assert.equal(audioPlays,1);assert.equal(audio.muted,true);
audio.play=async()=>{audioPlays++;};
assert.equal(await playRemoteMedia(video,audio,stream,true),false,'A user gesture can retry sound separately');
const empty={getAudioTracks:()=>[],getVideoTracks:()=>[]};
await playRemoteMedia(video,audio,empty,true);
assert.equal(videoPlays,3);assert.equal(audioPlays,2,'Empty streams must not show misleading autoplay errors');
console.log('Remote track aggregation, independent video playback and audio permission checks passed');
